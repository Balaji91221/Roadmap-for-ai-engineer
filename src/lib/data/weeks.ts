function getHook(weekNum: number, topic: string): string {
  if (CUSTOM_HOOKS[topic]) return CUSTOM_HOOKS[topic]
  const template = HOOK_TEMPLATES[(weekNum - 1) % HOOK_TEMPLATES.length]
  return template(topic)
}

