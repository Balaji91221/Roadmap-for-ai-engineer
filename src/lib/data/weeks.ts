function getPostTypes(div: number, difficulty: Difficulty): string[] {
  const base = ['Carousel: architecture diagram', 'Thread: key concepts & takeaways']
  if (difficulty === 'beginner') return [...base, 'Infographic: visual explainer']
  if (difficulty === 'expert') return [...base, 'Long-form: deep technical essay', 'Demo: live implementation walkthrough']
  if (div >= 4 && div <= 7) return [...base, 'Demo: agent in action (screen recording)', 'Thread: lessons from implementation']
  if (div === 8) return [...base, 'Demo: terminal walkthrough', 'Thread: production war stories']
  return [...base, 'Demo: code walkthrough with results']
}

